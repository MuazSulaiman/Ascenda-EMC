-- ── Quantity is always a whole number in this business — narrow from
-- ── NUMERIC(14,3) to INTEGER. Any existing fractional test rows are rounded
-- ── to the nearest whole number rather than failing the migration. Safe to
-- ── re-run: ALTER COLUMN ... TYPE INTEGER is a no-op once the column is
-- ── already INTEGER (confirmed empirically — round() still applies cleanly
-- ── via the implicit int->numeric cast, so this never errors on rerun).
ALTER TABLE quotation_lines          ALTER COLUMN quantity TYPE INTEGER USING ROUND(quantity)::INTEGER;
ALTER TABLE quotation_revision_lines ALTER COLUMN quantity TYPE INTEGER USING ROUND(quantity)::INTEGER;

-- ── A quotation must never have two lines for the same product — the UI
-- ── now blocks this too, but this is the DB-level backstop (matches the
-- ── existing UNIQUE(quotation_id, line_no) precedent above).
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'quotation_lines'::regclass
          AND conname  = 'quotation_lines_quotation_id_product_id_key'
    ) THEN
        ALTER TABLE quotation_lines
            ADD CONSTRAINT quotation_lines_quotation_id_product_id_key
            UNIQUE (quotation_id, product_id);
    END IF;
END $$;

-- ── Line items are now unlimited (was capped at 14 per quotation) --
-- drop the upper bound on the existing live table, keep the lower bound.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'quotation_lines'::regclass
          AND conname  = 'quotation_lines_line_no_check'
          AND pg_get_constraintdef(oid) LIKE '%<=%14%'
    ) THEN
        ALTER TABLE quotation_lines DROP CONSTRAINT quotation_lines_line_no_check;
        ALTER TABLE quotation_lines ADD CONSTRAINT quotation_lines_line_no_check CHECK (line_no >= 1);
    END IF;
END $$;
