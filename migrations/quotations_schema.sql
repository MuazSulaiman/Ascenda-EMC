CREATE TABLE IF NOT EXISTS quotation_requests (
    quotation_id      BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_number  TEXT    NOT NULL UNIQUE,
    customer_id       INTEGER NOT NULL REFERENCES customers(customer_id),
    rep_user_id       INTEGER NOT NULL REFERENCES users(user_id),
    quotation_date    DATE    NOT NULL DEFAULT CURRENT_DATE,
    vat_rate          NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (vat_rate BETWEEN 0 AND 100),

    remarks           TEXT,
    validity_days     INTEGER CHECK (validity_days IN (30, 60, 90, 180, 365)) NOT NULL,
    delivery_terms    TEXT CHECK (delivery_terms IN (
                           'Immediate', '15 Days', '30 Days', '45 Days',
                           '60 Days', '90 Days', '120 Days'
                       )) NOT NULL,
    payment_terms     TEXT CHECK (payment_terms IN (
                           'Cash in Advance', 'Cash on Delivery', '15 Days', '30 Days',
                           '60 Days', '90 Days', '120 Days', 'As per Agreed Policy'
                       )) NOT NULL,

    status    TEXT NOT NULL DEFAULT 'IN_REVIEW' CHECK (status IN (
                   'IN_REVIEW', 'EDIT_REQUESTED', 'REJECTED', 'APPROVED', 'DONE', 'WITHDRAWN'
               )),
    version   INTEGER NOT NULL DEFAULT 0,

    submitted_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    submitted_by  INTEGER NOT NULL REFERENCES users(user_id),

    manager_user_id     INTEGER REFERENCES users(user_id),
    manager_decided_at  TIMESTAMPTZ,
    manager_comment     TEXT,

    coordinator_user_id  INTEGER REFERENCES users(user_id),
    coordinator_done_at  TIMESTAMPTZ,
    coordinator_note     TEXT,
    odoo_reference        TEXT,

    withdrawn_at       TIMESTAMPTZ,
    withdrawn_by        INTEGER REFERENCES users(user_id),
    withdrawal_reason    TEXT,

    is_deleted   BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at    TIMESTAMPTZ,
    deleted_by     INTEGER REFERENCES users(user_id)
);

CREATE TABLE IF NOT EXISTS quotation_lines (
    line_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id  BIGINT NOT NULL REFERENCES quotation_requests(quotation_id) ON DELETE CASCADE,
    line_no       SMALLINT NOT NULL CHECK (line_no >= 1),
    product_id    TEXT NOT NULL REFERENCES items(product_id),
    quantity      INTEGER NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
    discount_pct  NUMERIC(5,2)  NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (quotation_id, line_no),
    UNIQUE (quotation_id, product_id)
);

CREATE TABLE IF NOT EXISTS quotation_revisions (
    revision_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id    BIGINT NOT NULL REFERENCES quotation_requests(quotation_id) ON DELETE CASCADE,
    revision_no     SMALLINT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by      INTEGER NOT NULL REFERENCES users(user_id),

    customer_id     INTEGER NOT NULL REFERENCES customers(customer_id),
    quotation_date  DATE NOT NULL,
    vat_rate        NUMERIC(5,2) NOT NULL,
    remarks         TEXT,
    validity_days   INTEGER NOT NULL,
    delivery_terms  TEXT NOT NULL,
    payment_terms   TEXT NOT NULL,

    subtotal        NUMERIC(16,2) NOT NULL,
    vat_amount      NUMERIC(16,2) NOT NULL,
    grand_total     NUMERIC(16,2) NOT NULL,

    UNIQUE (quotation_id, revision_no)
);

CREATE TABLE IF NOT EXISTS quotation_revision_lines (
    revision_line_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id              BIGINT NOT NULL REFERENCES quotation_revisions(revision_id) ON DELETE CASCADE,
    line_no                  SMALLINT NOT NULL,
    product_id               TEXT NOT NULL REFERENCES items(product_id),
    article_number_snapshot  TEXT,
    description_snapshot     TEXT,
    quantity                 INTEGER NOT NULL,
    unit_price                NUMERIC(14,2) NOT NULL,
    discount_pct               NUMERIC(5,2) NOT NULL,
    line_total                  NUMERIC(16,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS quotation_status_events (
    event_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id    BIGINT NOT NULL REFERENCES quotation_requests(quotation_id) ON DELETE CASCADE,
    event_type      TEXT NOT NULL CHECK (event_type IN (
                         'SUBMITTED', 'RESUBMITTED', 'EDIT_REQUESTED', 'APPROVED',
                         'REJECTED', 'WITHDRAWN', 'RETURNED_FOR_REVISION', 'MARKED_DONE'
                     )),
    actor_user_id   INTEGER NOT NULL REFERENCES users(user_id),
    from_status     TEXT,
    to_status       TEXT NOT NULL,
    comment         TEXT,
    revision_id     BIGINT REFERENCES quotation_revisions(revision_id),
    at_utc          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS quotation_number_counters (
    year     INTEGER PRIMARY KEY,
    last_seq INTEGER NOT NULL DEFAULT 0
);

