-- ── users.role CHECK migration — add 'sales coordinator' ────────────────────────
DO $$
DECLARE
    _conname TEXT;
    _condef  TEXT;
BEGIN
    SELECT con.conname, pg_get_constraintdef(con.oid) INTO _conname, _condef
    FROM pg_constraint con
    JOIN pg_class rel ON rel.oid = con.conrelid
    WHERE rel.relname = 'users'
      AND con.contype = 'c'
      AND pg_get_constraintdef(con.oid) ILIKE '%role%'
    LIMIT 1;

    IF _conname IS NOT NULL AND _condef NOT ILIKE '%sales coordinator%' THEN
        EXECUTE format('ALTER TABLE users DROP CONSTRAINT %I', _conname);
        ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN (
            'admin', 'rep', 'maintenance', 'supervisor',
            'sales manager', 'biomedical manager', 'sales coordinator'
        ));
    END IF;
END $$;

